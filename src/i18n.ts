const dicts: Record<Locale, Dict> = { zh, en }
export type TKey = keyof Dict

function initial(): Locale {
  try {
    const saved = store.getItem(KEY)
    if (saved === 'zh' || saved === 'en') return saved
  } catch {
    /* 無痕模式等情況忽略 */
  }
  // 依 CrazyGames 回報的語言，取不到時看瀏覽器；中文顯示中文，其餘預設英文
  const lang = platformLocale() ?? (typeof navigator !== 'undefined' ? navigator.language : '')
  return lang?.toLowerCase().startsWith('zh') ? 'zh' : 'en'
}

export const locale = ref<Locale>(initial())

function applyDocument() {
  if (typeof document === 'undefined') return
  document.documentElement.lang = locale.value === 'zh' ? 'zh-Hant-TW' : 'en'
  document.title = dicts[locale.value].title
}
applyDocument()

export function setLocale(l: Locale) {
  locale.value = l
  applyDocument()
  try {
    store.setItem(KEY, l)
  } catch {
    /* ignore */
  }
}

export function t(key: TKey, params?: Record<string, string | number>): string {
  let s = dicts[locale.value][key]
  // 取代值用函式傳入：玩家暱稱裡的 $& / $` 等字樣不會被當成取代樣式
  if (params) for (const k in params) s = s.replaceAll(`{${k}}`, () => String(params[k]))
  // {min}：一局的分鐘數（CrazyGames 短局 4 分鐘、網站版 10 分鐘）
  return s.replaceAll('{min}', String(CONFIG.matchDuration / 60))
}
